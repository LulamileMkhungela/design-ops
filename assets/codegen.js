/* ── shared helpers ─────────────────────────────────────────── */

/** Render a [prop, value] rule list as CSS declarations. */
function decls(rules, indent) {
  return rules.map((r) => indent + r[0] + ": " + r[1] + ";").join("\n")
}

/** Swap var(--token-name) for the literal token value (targets without CSS vars). */
function toRaw(str) {
  return str.replace(/var\(--([\w-]+)\)/g, (m, name) => {
    const found = TOKENS.find((t) => t.css === "--" + name)
    return found ? found.v : m
  })
}

/** camelCase a CSS property (React Native StyleSheet). */
function camel(prop) {
  return prop.replace(/-([a-z])/g, (m, c) => c.toUpperCase())
}

/** PascalCase a component id: data-table → DataTable. */
function pascal(id) {
  return id
    .split("-")
    .map((s) => s[0].toUpperCase() + s.slice(1))
    .join("")
}

/** Does this component's schema drive a dynamic variant/size class? */
function hasVariant(c) {
  return (
    c.props.some((p) => p.n === "variant") &&
    Object.keys(c.css.variants).length > 0
  )
}
function hasSize(c) {
  return (
    c.props.some((p) => p.n === "size") &&
    Object.keys(c.css.modifiers).length > 0
  )
}

/** A destructure list with defaults: "variant = 'primary', size = 'md'". */
function withDefaults(c) {
  return c.props.map((p) => p.n + " = " + (p.d === "—" ? "''" : p.d)).join(", ")
}

/** Header comment stamped on every generated snippet (line-comment style). */
function genHeader(c, targetLabel) {
  return [
    "// ─────────────────────────────────────────",
    "// " + c.name + " · generated by DesignOps",
    "// Figma spec: " + c.figmaPath,
    "// Target: " + targetLabel,
    "// Values come from shipped tokens — never hard-code.",
    "// ─────────────────────────────────────────",
  ].join("\n")
}

/** Same header for file formats that only support HTML comments. */
function genHeaderHTML(c, targetLabel) {
  return (
    "<!-- " +
    c.name +
    " · generated by DesignOps · Figma: " +
    c.figmaPath +
    " · Target: " +
    targetLabel +
    " -->"
  )
}

/* ── CSS / SCSS ─────────────────────────────────────────────── */

function genCSS(c) {
  const blocks = ["." + c.cls + " {\n" + decls(c.css.base, "  ") + "\n}"]
  for (const [v, rules] of Object.entries(c.css.variants)) {
    blocks.push(
      "/* variant: " +
        v +
        " */\n." +
        c.cls +
        "--" +
        v +
        " {\n" +
        decls(rules, "  ") +
        "\n}"
    )
  }
  for (const [m, rules] of Object.entries(c.css.modifiers)) {
    blocks.push(
      "/* modifier: " +
        m +
        " */\n." +
        c.cls +
        "--" +
        m +
        " {\n" +
        decls(rules, "  ") +
        "\n}"
    )
  }
  return (
    "/* " +
    c.name +
    ' — generated by DesignOps from the Figma spec "' +
    c.figmaPath +
    '"\n' +
    "   Selector convention: " +
    c.tag +
    " renders the class " +
    c.cls +
    ". */\n\n" +
    blocks.join("\n\n")
  )
}

function genSCSS(c) {
  return genCSS(c)
    .split("\n")
    .map((l) => l.replace(/var\(--([\w-]+)\)/g, "$$$1"))
    .join("\n")
}

/* ── React (Next.js / Remix via flavor note) ────────────────── */

function genReact(c, flavor) {
  const name = pascal(c.id)
  const l = []
  l.push(
    genHeader(
      c,
      flavor === "next"
        ? "React · Next.js App Router"
        : flavor === "remix"
          ? "React · Remix"
          : "React 18 + TypeScript"
    )
  )
  if (flavor === "next")
    l.push("// App Router: this is a Client Component if it handles events.")
  if (flavor === "remix")
    l.push(
      "// Remix: register the token stylesheet once in app/root.tsx links()."
    )
  if (c.id === "button") return genReactButton(c, l, name)
  if (c.id === "input") return genReactInput(c, l, name)
  if (c.id === "card") return genReactCard(c, l, name)
  if (c.id === "data-table") return genReactTable(c, l, name)
  return genReactGeneric(c, l, name)
}

function genReactButton(c, l, name) {
  const variant = c.props.find((p) => p.n === "variant")
  const size = c.props.find((p) => p.n === "size")
  l.push("import { forwardRef } from 'react';")
  l.push("import type { ButtonHTMLAttributes, ReactNode } from 'react';")
  l.push(
    "import './" +
      c.id +
      ".css'; // CSS-tab output — or skip: npm i @designops/react"
  )
  l.push("")
  l.push(
    "export interface " +
      name +
      "Props extends ButtonHTMLAttributes<HTMLButtonElement> {"
  )
  if (variant) l.push("  /** Figma: variant */\n  variant?: " + variant.t + ";")
  if (size) l.push("  /** Figma: size */\n  size?: " + size.t + ";")
  l.push("  /** Figma: loading */\n  loading?: boolean;")
  l.push("  children?: ReactNode;")
  l.push("}")
  l.push("")
  l.push(
    "export const " +
      name +
      " = forwardRef<HTMLButtonElement, " +
      name +
      "Props>(function " +
      name +
      "("
  )
  l.push(
    "  { variant = " +
      (variant ? variant.d : "'primary'") +
      ", size = " +
      (size ? size.d : "'md'") +
      ", loading = false, disabled = false, className = '', children, type = 'button', ...rest },"
  )
  l.push("  ref")
  l.push(") {")
  l.push(
    "  const cls = ['" +
      c.cls +
      "', `" +
      c.cls +
      "--${variant}`, `" +
      c.cls +
      "--${size}`, className]"
  )
  l.push("    .filter(Boolean)")
  l.push("    .join(' ');")
  l.push("  return (")
  l.push("    <button")
  l.push("      ref={ref}")
  l.push("      type={type}")
  l.push("      className={cls}")
  l.push("      disabled={disabled || loading}")
  l.push("      aria-busy={loading || undefined}")
  l.push("      {...rest}")
  l.push("    >")
  l.push(
    "      {loading ? <span className='ds-spinner' aria-hidden='true' /> : null}"
  )
  l.push("      {children}")
  l.push("    </button>")
  l.push("  );")
  l.push("});")
  return l.join("\n")
}

function genReactCard(c, l, name) {
  const variant = c.props.find((p) => p.n === "variant")
  l.push("import type { ElementType, HTMLAttributes, ReactNode } from 'react';")
  l.push("import './" + c.id + ".css'; // or npm i @designops/react")
  l.push("")
  l.push(
    "export interface " +
      name +
      "Props extends HTMLAttributes<HTMLDivElement> {"
  )
  if (variant) l.push("  /** Figma: variant */\n  variant?: " + variant.t + ";")
  l.push("  /** Keep the styling contract when the semantics change. */")
  l.push("  as?: ElementType;")
  l.push("  children?: ReactNode;")
  l.push("}")
  l.push("")
  l.push(
    "export function " +
      name +
      "({ variant = " +
      (variant ? variant.d : "'default'") +
      ", as: Tag = '" +
      c.element +
      "', className = '', children, ...rest }: " +
      name +
      "Props) {"
  )
  l.push(
    "  const cls = ['" +
      c.cls +
      "', variant !== 'default' ? `" +
      c.cls +
      "--${variant}` : '', className]"
  )
  l.push("    .filter(Boolean)")
  l.push("    .join(' ');")
  l.push("  return (")
  l.push("    <Tag className={cls} {...rest}>")
  l.push("      {children}")
  l.push("    </Tag>")
  l.push("  );")
  l.push("}")
  return l.join("\n")
}

