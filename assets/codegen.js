/* ── React Native (tokens resolve to literal values) ────────── */

function genRN(c) {
  const name = pascal(c.id);
  const l = [];
  l.push(genHeader(c, 'React Native — tokens resolve to values; no CSS vars on mobile'));
  l.push("import { StyleSheet } from 'react-native';");
  l.push('');
  l.push('export const ' + name.charAt(0).toLowerCase() + name.slice(1) + 'Styles = StyleSheet.create({');
  l.push('  base: {');
  c.css.base.forEach(([p, v]) => l.push('    ' + camel(p) + ": '" + toRaw(v) + "',"));
  l.push('  },');
  for (const [vname, rules] of Object.entries(c.css.variants)) {
    l.push('  ' + vname + ': {');
    rules.forEach(([p, val]) => l.push('    ' + camel(p) + ": '" + toRaw(val) + "',"));
    l.push('  },');
  }
  l.push('});');
  l.push('');
  l.push('// Same Figma names, platform-native values — zero drift between web and mobile.');
  return l.join('\n');
}

/* ── Tailwind ───────────────────────────────────────────────── */

const TW_MAP = {
  display: (v) => ({ 'inline-flex': 'inline-flex', flex: 'flex' }[v] || ''),
  'align-items': (v) => ({ center: 'items-center' }[v] || ''),
  'justify-content': (v) => ({ center: 'justify-center' }[v] || ''),
  cursor: (v) => ({ pointer: 'cursor-pointer' }[v] || ''),
  border: (v) => (v === 'none' ? 'border-0' : ''),
  outline: (v) => (v === 'none' ? 'outline-none' : ''),
  'border-collapse': () => 'border-collapse',
};

function twFor(prop, value) {
  if (TW_MAP[prop] !== undefined) return TW_MAP[prop](value);
  const arb = (p) => p + '-[' + value + ']';
  switch (prop) {
    case 'background':
    case 'background-color': return value.includes('var(') || value.includes('rgba') ? arb('bg') : '';
    case 'color':            return 'text-[color:' + value + ']';   // disambiguated from font-size
    case 'gap':              return arb('gap');
    case 'border-radius':    return arb('rounded');
    case 'font-size':        return 'text-[length:' + value + ']';  // disambiguated from color
    case 'font-weight':      return arb('font');
    case 'box-shadow':       return arb('shadow');
    case 'width':            return arb('w');
    case 'height':           return arb('h');
    case 'transition':       return 'transition';
    case 'animation':        return arb('animate');
    case 'padding': {
      const parts = value.split(' ');
      if (parts.length === 2) return 'py-[' + parts[0] + '] px-[' + parts[1] + ']';
      return 'p-[' + value + ']';
    }
    default: return '';
  }
}

function genTailwind(c) {
  const l = [];
  l.push(genHeaderHTML(c, 'Tailwind CSS'));
  l.push('<!-- tailwind.config.js → export default { presets: [require("@designops/tokens-tailwind")] } -->');
  const firstVar = Object.keys(c.css.variants)[0];
  const cls = [
    ...c.css.base.map(([p, v]) => twFor(p, v)),
    ...(firstVar ? c.css.variants[firstVar].map(([p, v]) => twFor(p, v)) : []),
  ].filter(Boolean).join(' ');
  l.push('');
  l.push('<!-- ' + c.name + (firstVar ? ' · variant: ' + firstVar : '') + ' — tokens resolve at runtime -->');
  l.push('<' + c.element + ' class="' + cls + '">' + c.name + ' content</' + c.element + '>');
  return l.join('\n');
}

