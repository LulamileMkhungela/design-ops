/* ── token artifact builders (browser-side export) ────────────
   Mirrors tools/ship.mjs so the UI “Export tokens” button produces
   exactly what the CI build writes to dist/. */
function exportTokens(format) {
  const head =
    "/* AUTO-GENERATED · DesignOps tokens v3.0.0 · source: tokens/tokens.json (Figma Variables) */\n"
  if (format === "css") {
    return (
      head +
      "\n:root {\n" +
      TOKENS.map((t) => "  " + t.css + ": " + t.v + ";").join("\n") +
      "\n}\n"
    )
  }
  if (format === "scss") {
    return (
      head +
      "\n" +
      TOKENS.map((t) => t.scss + ": " + t.v + ";").join("\n") +
      "\n"
    )
  }
  if (format === "ts") {
    return (
      head +
      "\nexport const tokens = {\n" +
      TOKENS.map(
        (t) => "  /** " + t.f + " */\n  " + t.js + ": '" + t.v + "',"
      ).join("\n") +
      "\n} as const;\n\nexport type TokenName = keyof typeof tokens;\n"
    )
  }
  if (format === "tailwind") {
    return (
      head +
      "\nmodule.exports = " +
      JSON.stringify(
        {
          theme: {
            extend: Object.fromEntries(
              TOKENS.map((t) => [t.css.slice(2), t.v])
            ),
          },
        },
        null,
        2
      ) +
      ";\n"
    )
  }
  return (
    JSON.stringify(
      {
        $meta: {
          name: "designops-tokens",
          version: "3.0.0",
          owner: "Lulamile Mkhungela",
        },
        tokens: TOKENS.map((t) => ({ name: t.f, value: t.v, type: t.t })),
      },
      null,
      2
    ) + "\n"
  )
}
