/* ── Tailwind ───────────────────────────────────────────────── */

const TW_MAP = {
  display: (v) => ({ "inline-flex": "inline-flex", flex: "flex" })[v] || "",
  "align-items": (v) => ({ center: "items-center" })[v] || "",
  "justify-content": (v) => ({ center: "justify-center" })[v] || "",
  cursor: (v) => ({ pointer: "cursor-pointer" })[v] || "",
  border: (v) => (v === "none" ? "border-0" : ""),
  outline: (v) => (v === "none" ? "outline-none" : ""),
  "border-collapse": () => "border-collapse",
}

function twFor(prop, value) {
  if (TW_MAP[prop] !== undefined) return TW_MAP[prop](value)
  const arb = (p) => p + "-[" + value + "]"
  switch (prop) {
    case "background":
    case "background-color":
      return value.includes("var(") || value.includes("rgba") ? arb("bg") : ""
    case "color":
      return "text-[color:" + value + "]" // disambiguated from font-size
    case "gap":
      return arb("gap")
    case "border-radius":
      return arb("rounded")
    case "font-size":
      return "text-[length:" + value + "]" // disambiguated from color
    case "font-weight":
      return arb("font")
    case "box-shadow":
      return arb("shadow")
    case "width":
      return arb("w")
    case "height":
      return arb("h")
    case "transition":
      return "transition"
    case "animation":
      return arb("animate")
    case "padding": {
      const parts = value.split(" ")
      if (parts.length === 2)
        return "py-[" + parts[0] + "] px-[" + parts[1] + "]"
      return "p-[" + value + "]"
    }
    default:
      return ""
  }
}

