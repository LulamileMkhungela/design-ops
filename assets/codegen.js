/* ── shared helpers ─────────────────────────────────────────── */

/** Render a [prop, value] rule list as CSS declarations. */
function decls(rules, indent) {
  return rules.map((r) => indent + r[0] + ': ' + r[1] + ';').join('\n');
}

/** Swap var(--token-name) for the literal token value (targets without CSS vars). */
function toRaw(str) {
  return str.replace(/var\(--([\w-]+)\)/g, (m, name) => {
    const found = TOKENS.find((t) => t.css === '--' + name);
    return found ? found.v : m;
  });
}

/** camelCase a CSS property (React Native StyleSheet). */
function camel(prop) { return prop.replace(/-([a-z])/g, (m, c) => c.toUpperCase()); }

/** PascalCase a component id: data-table → DataTable. */
function pascal(id) { return id.split('-').map((s) => s[0].toUpperCase() + s.slice(1)).join(''); }

/** Does this component's schema drive a dynamic variant/size class? */
function hasVariant(c) { return c.props.some((p) => p.n === 'variant') && Object.keys(c.css.variants).length > 0; }
function hasSize(c)    { return c.props.some((p) => p.n === 'size') && Object.keys(c.css.modifiers).length > 0; }

/** A destructure list with defaults: "variant = 'primary', size = 'md'". */
function withDefaults(c) {
  return c.props.map((p) => p.n + ' = ' + (p.d === '—' ? "''" : p.d)).join(', ');
}

/** Header comment stamped on every generated snippet (line-comment style). */
function genHeader(c, targetLabel) {
  return [
    '// ─────────────────────────────────────────',
    '// ' + c.name + ' · generated by DesignOps',
    '// Figma spec: ' + c.figmaPath,
    '// Target: ' + targetLabel,
    '// Values come from shipped tokens — never hard-code.',
    '// ─────────────────────────────────────────',
  ].join('\n');
}

/** Same header for file formats that only support HTML comments. */
function genHeaderHTML(c, targetLabel) {
  return '<!-- ' + c.name + ' · generated by DesignOps · Figma: ' + c.figmaPath + ' · Target: ' + targetLabel + ' -->';
}

/* ── CSS / SCSS ─────────────────────────────────────────────── */

function genCSS(c) {
  const blocks = ['.' + c.cls + ' {\n' + decls(c.css.base, '  ') + '\n}'];
  for (const [v, rules] of Object.entries(c.css.variants)) {
    blocks.push('/* variant: ' + v + ' */\n.' + c.cls + '--' + v + ' {\n' + decls(rules, '  ') + '\n}');
  }
  for (const [m, rules] of Object.entries(c.css.modifiers)) {
    blocks.push('/* modifier: ' + m + ' */\n.' + c.cls + '--' + m + ' {\n' + decls(rules, '  ') + '\n}');
  }
  return '/* ' + c.name + ' — generated by DesignOps from the Figma spec "' + c.figmaPath + '"\n' +
    '   Selector convention: ' + c.tag + ' renders the class ' + c.cls + '. */\n\n' + blocks.join('\n\n');
}

function genSCSS(c) {
  return genCSS(c).split('\n').map((l) => l.replace(/var\(--([\w-]+)\)/g, '$$$1')).join('\n');
}

/* ── React (Next.js / Remix via flavor note) ────────────────── */

function genReact(c, flavor) {
  const name = pascal(c.id);
  const l = [];
  l.push(genHeader(c, flavor === 'next' ? 'React · Next.js App Router' : flavor === 'remix' ? 'React · Remix' : 'React 18 + TypeScript'));
  if (flavor === 'next') l.push('// App Router: this is a Client Component if it handles events.');
  if (flavor === 'remix') l.push('// Remix: register the token stylesheet once in app/root.tsx links().');
  l.push("import type { ReactNode } from 'react';");
  l.push("import './" + c.id + ".css'; // CSS-tab output — or skip: npm i @designops/react");
  l.push('');
  l.push('export interface ' + name + 'Props {');
  c.props.forEach((p) => l.push('  /** Figma: ' + p.figma + ' */\n  ' + p.n + '?: ' + p.t + ';'));
  l.push('  children?: ReactNode;');
  l.push('}');
  l.push('');
  l.push('export function ' + name + '({ ' + withDefaults(c) + ', children }: ' + name + 'Props) {');
  if (hasVariant(c) || hasSize(c)) {
    l.push('  const cls = [');
    l.push("    '" + c.cls + "',");
    if (hasVariant(c)) l.push("    variant && '" + c.cls + "--' + variant,");
    if (hasSize(c)) l.push("    size && '" + c.cls + "--' + size,");
    l.push("  ].join(' ');");
  }
  const clsAttr = hasVariant(c) || hasSize(c) ? 'className={cls}' : 'className="' + c.cls + '"';
  l.push('  return (');
  if (c.id === 'button') {
    l.push('    <button ' + clsAttr + ' disabled={disabled || loading} aria-busy={loading || undefined}>');
    l.push('      {loading && <span className="ds-spinner" aria-hidden="true" />}');
    l.push('      {children}');
    l.push('    </button>');
  } else if (c.id === 'input') {
    l.push('    <label className="ds-field">');
    l.push("      <span className=\"ds-label\">{label}{required ? ' *' : ''}</span>");
    l.push('      <input ' + clsAttr + ' type={type} disabled={disabled} aria-invalid={Boolean(error)} />');
    l.push('      {error ? <span role="alert" className="ds-error">{error}</span>');
    l.push('             : hint ? <span className="ds-hint">{hint}</span> : null}');
    l.push('    </label>');
  } else {
    l.push('    <' + c.element + ' ' + clsAttr + '>');
    l.push('      {children}');
    l.push('    </' + c.element + '>');
  }
  l.push('  );');
  l.push('}');
  return l.join('\n');
}

/* ── Vue (Nuxt via flavor note) ─────────────────────────────── */

function genVue(c, flavor) {
  const l = [];
  l.push(genHeader(c, flavor === 'nuxt' ? 'Vue 3 · Nuxt (module @designops/nuxt)' : 'Vue 3 · Single File Component'));
  if (flavor === 'nuxt') l.push('// The Nuxt module auto-registers this as <Ds' + pascal(c.id) + ' /> app-wide.');
  l.push('<script setup lang="ts">');
  l.push('// Props mirror the Figma component properties 1:1.');
  l.push('interface Props {');
  c.props.forEach((p) => l.push('  /** Figma: ' + p.figma + ' */\n  ' + p.n + '?: ' + p.t + ';'));
  l.push('}');
  l.push('withDefaults(defineProps<Props>(), { ' + c.props.map((p) => p.n + ': ' + (p.d === '—' ? "''" : p.d)).join(', ') + ' });');
  l.push('</script>');
  l.push('');
  l.push('<template>');
  const clsBits = ["'" + c.cls + "'"];
  if (hasVariant(c)) clsBits.push("`" + c.cls + '--${variant}`');
  if (hasSize(c)) clsBits.push("`" + c.cls + '--${size}`');
  const clsExpr = ':class="[' + clsBits.join(', ') + ']"';
  if (c.id === 'button') {
    l.push('  <button ' + clsExpr + ' :disabled="disabled || loading" :aria-busy="loading || undefined">');
    l.push('    <span v-if="loading" class="ds-spinner" aria-hidden="true" />');
    l.push('    <slot />');
    l.push('  </button>');
  } else {
    l.push('  <' + c.element + ' ' + clsExpr + '>');
    l.push('    <slot />');
    l.push('  </' + c.element + '>');
  }
  l.push('</template>');
  l.push('');
  l.push('<style scoped>');
  l.push('/* Token variables resolve from the shipped tokens.css — never hard-coded. */');
  l.push('.' + c.cls + ' {');
  l.push(decls(c.css.base, '  '));
  l.push('}');
  l.push('</style>');
  return l.join('\n');
}

/* ── Svelte ─────────────────────────────────────────────────── */

function genSvelte(c) {
  const l = [];
  l.push(genHeaderHTML(c, 'Svelte / SvelteKit'));
  l.push('<script lang="ts">');
  c.props.forEach((p) => l.push('  /** Figma: ' + p.figma + ' */\n  export let ' + p.n + ': ' + p.t + ' = ' + (p.d === '—' ? "''" : p.d) + ';'));
  l.push('  /** Assembled from variant/size — same naming as the CSS target. */');
  const bits = ["'" + c.cls + "'"];
  if (hasVariant(c)) bits.push("`" + c.cls + '--${variant}`');
  if (hasSize(c)) bits.push("`" + c.cls + '--${size}`');
  l.push('  $: cls = ' + (bits.length > 1 ? '[' + bits.join(', ') + "].join(' ')" : bits[0]) + ';');
  l.push('</script>');
  l.push('');
  if (c.id === 'button') {
    l.push('<button class={cls} disabled={disabled || loading} aria-busy={loading || undefined}>');
    l.push('  {#if loading}<span class="ds-spinner" aria-hidden="true" />{/if}');
    l.push('  <slot />');
    l.push('</button>');
  } else {
    l.push('<' + c.element + ' class={cls}>');
    l.push('  <slot />');
    l.push('</' + c.element + '>');
  }
  l.push('');
  l.push('<style>');
  l.push('  .' + c.cls + ' {');
  l.push(decls(c.css.base, '    '));
  l.push('  }');
  l.push('</style>');
  return l.join('\n');
}

/* ── Angular (Ionic via flavor note) ────────────────────────── */

function genAngular(c, flavor) {
  const name = pascal(c.id);
  const l = [];
  l.push(genHeader(c, flavor === 'ionic' ? 'Angular · Ionic (tokens mapped onto Ionic vars)' : 'Angular 17 standalone'));
  if (flavor === 'ionic') l.push('// Ship note: tokens.css also sets --ion-color-primary: var(--color-primary-900), etc.');
  l.push("import { Component, Input } from '@angular/core';");
  l.push("import { NgIf } from '@angular/common';");
  l.push('');
  l.push('@Component({');
  l.push("  selector: '" + c.tag + "',");
  l.push('  standalone: true,');
  if (c.id === 'button') {
    l.push('  imports: [NgIf],');
    l.push('  template: `');
    l.push('    <button [class]="classes" [disabled]="disabled || loading" [attr.aria-busy]="loading || null">');
    l.push('      <span *ngIf="loading" class="ds-spinner" aria-hidden="true"></span>');
    l.push('      <ng-content />');
    l.push('    </button>`,');
  } else {
    l.push('  template: `<' + c.element + ' [class]="classes"><ng-content /></' + c.element + '>`,');
  }
  l.push('  styles: [`');
  l.push('    /* Values resolve from shipped token CSS variables */');
  l.push('    .' + c.cls + ' {');
  l.push(decls(c.css.base, '      '));
  l.push('    }');
  const firstVar = Object.entries(c.css.variants)[0];
  if (firstVar && hasVariant(c)) {
    l.push('    .' + c.cls + '--' + firstVar[0] + ' {');
    l.push(decls(firstVar[1], '      '));
    l.push('    }');
  }
  l.push('  `],');
  l.push('})');
  l.push('export class ' + name + 'Component {');
  c.props.forEach((p) => {
    l.push('  /** Figma property: ' + p.figma + ' */');
    l.push('  @Input() ' + p.n + ': ' + p.t + ' = ' + (p.d === '—' ? "''" : p.d) + ';');
  });
  const parts = ["'" + c.cls + "'"];
  if (hasVariant(c)) parts.push("`" + c.cls + '--${this.variant}`');
  if (hasSize(c)) parts.push("`" + c.cls + '--${this.size}`');
  l.push('  get classes(): string {');
  l.push('    return [' + parts.join(', ') + "].join(' ');");
  l.push('  }');
  l.push('}');
  return l.join('\n');
}

